#!/usr/bin/env node
// Builds the single prebuilt module the package `pi.extensions` entry points at.
// Keep the `.ts` extension on the output: jiti's transpile path (used for a
// `.ts` entry) resolves `@earendil-works/*` through the host's own module
// instances, while the native-import path used for a `.js` entry can load a
// second copy of pi, or fail to resolve it at all.
import { readFileSync } from "node:fs";
import { build } from "esbuild";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const externals = [
	...Object.keys(pkg.dependencies ?? {}),
	...Object.keys(pkg.peerDependencies ?? {}),
	"@earendil-works/*",
];

await build({
	entryPoints: ["src/index.ts"],
	outfile: "dist/index.ts",
	bundle: true,
	format: "esm",
	platform: "node",
	target: "node20",
	external: [...new Set(externals)],
	banner: {
		js: "// Generated by scripts/build.js from src/. Do not edit; run `npm run build`.",
	},
});
